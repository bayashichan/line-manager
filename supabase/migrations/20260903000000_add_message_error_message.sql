-- =============================================================================
-- 配信失敗の理由を残せるようにする
--
-- これまで LINE API が返したエラー（400の詳細など）はサーバーログにしか出ておらず、
-- 管理画面には赤い×が出るだけで原因が分からなかった。
-- 失敗時の理由を messages.error_message に保存し、配信履歴から確認できるようにする。
-- =============================================================================

ALTER TABLE messages ADD COLUMN IF NOT EXISTS error_message TEXT;

COMMENT ON COLUMN messages.error_message IS '配信失敗時の理由（LINE APIのエラー本文、または送信前バリデーションのエラー）';
