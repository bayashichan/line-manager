-- =============================================================================
-- form_responses: 申込時点のLINE表示名
--
-- 申込者一覧・回答一覧のLINE名は、友だち情報（line_users）から引いて出している。
-- そのため友だちになっていない人（LIFFでログインして申し込んだだけの人）は
-- LINE名が出ず、入力された名前だけでは誰なのか分からなかった。
--
-- 申込時にLIFFのプロフィールから受け取った表示名を回答ごとに控えておき、
-- 友だち情報に名前が無いときの代わりに使う。
-- 既存の回答は申込時点の名前が分からないので NULL（記録なし）のままにする。
-- =============================================================================

ALTER TABLE form_responses
    ADD COLUMN IF NOT EXISTS line_display_name TEXT;

COMMENT ON COLUMN form_responses.line_display_name IS '申込時点のLINE表示名（LIFFのプロフィールから取得。本人が修正したときは修正時点の名前）。NULL = 記録なし（機能追加前の回答）';
