-- =============================================================================
-- 一斉配信・予約配信の二重送信防止
--
-- 送信処理を始めた時刻。NULL の配信だけが「送信する権利」を取れる
-- （src/lib/messaging/claim.ts）。予約配信が QStash と Cron の両方から同時に
-- 処理されたり、送信APIが2回呼ばれたりしても、送信されるのは1回だけになる。
--
-- 既存の行は NULL のまま。送信済み・失敗・キャンセルの配信は状態の条件で
-- 除外されるので、過去の配信が送り直されることはない。
-- =============================================================================

ALTER TABLE messages ADD COLUMN IF NOT EXISTS send_started_at TIMESTAMPTZ;

COMMENT ON COLUMN messages.send_started_at IS '送信処理を開始した時刻（二重送信防止用）';
